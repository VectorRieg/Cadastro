    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    String email = jTextField2.getText().trim();
    if (email.isEmpty()) 
    {
        javax.swing.JOptionPane.showMessageDialog(this, "Digite o email.");
        return;
    }

    try {
        if (!new CadastroDao().temEmail(email)) 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Email não encontrado.");
            return;
        }
    } 
    catch (RuntimeException ex) 
    {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao acessar o banco de dados.");
        return;
    }
    jLabel1.setVisible(false);
    jTextField2.setVisible(false);
    jButton1.setVisible(false);
    jLabel2.setVisible(true);
    jTextField4.setVisible(true);
    jButton2.setVisible(true);
    }//GEN-LAST:event_jButton1ActionPerformed
