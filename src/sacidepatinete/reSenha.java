    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    String email = jTextField2.getText().trim();
        String novaSenha = jTextField4.getText().trim();
        if (novaSenha.length() < 4) 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "A senha deve ter pelo menos 4 caracteres.");
                return;
        }

        try 
        {
            if (new CadastroDao().novaSenha(email, novaSenha)) 
            {
                javax.swing.JOptionPane.showMessageDialog(this, "Senha alterada com sucesso!");
                dispose();   
            } 
            else 
            {
                javax.swing.JOptionPane.showMessageDialog(this, "Não foi possível alterar a senha.");
            }
        } 
        catch (RuntimeException ex) 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao acessar o banco de dados.");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

